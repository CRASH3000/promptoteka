export function getKnowledgeArticlesByFilters(searchQuery, selectedCategory) {
  const normalizedQuery = searchQuery.trim().toLowerCase()

  return knowledgeArticles.filter((article) => {
    const matchesCategory =
      !selectedCategory || article.category === selectedCategory

    const matchesSearch =
      !normalizedQuery ||
      article.title.toLowerCase().includes(normalizedQuery) ||
      article.shortDescription.toLowerCase().includes(normalizedQuery) ||
      article.category.toLowerCase().includes(normalizedQuery) ||
      article.content.join(' ').toLowerCase().includes(normalizedQuery)

    return matchesCategory && matchesSearch
  })
}

export function findKnowledgeArticleById(articleId) {
  return knowledgeArticles.find((article) => article.id === articleId)
}